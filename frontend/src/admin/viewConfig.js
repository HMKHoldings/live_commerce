export function rowsForView(rows, config={}) {
  let result=config.filter ? rows.filter(config.filter) : rows;
  if(config.dedupeCustomers){
    const seen=new Set();
    result=result.filter(row=>{const key=row.userId||row.customer?.email||row.customer?.phone||row.customer?.name;if(!key||seen.has(key))return false;seen.add(key);return true;});
  }
  return result;
}
